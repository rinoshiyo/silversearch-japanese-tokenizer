// tokenize と isTokenizable の単体テスト。
// 期待値は設定 indexLastCharacter を有効にした時の形で書き、無効の時は末尾 1 文字を除いた形と比べる。
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { init, isTokenizable, tokenize } from "../src/silversearch-japanese-tokenizer";
import { withoutLastCharacters } from "./expected";

const cases = (rows: [string, string[]][]) => rows.map(([input, expected]) => ({ input, expected }));

describe.each([true, false])("indexLastCharacter: %s", last => {
  beforeAll(() => init({ indexLastCharacter: last }));
  afterAll(() => init({}));

  const expectTokens = (input: string, expected: string[]) => {
    expect(tokenize(input)).toEqual(last ? expected : withoutLastCharacters(expected));
  };

  describe("日本語の連続の分割", () => {
    it.each(cases([
      ["日", ["日"]],
      ["日本", ["日本", "本"]],
      ["日本株", ["日本", "本株", "株"]],
      ["東京都", ["東京", "京都", "都"]],
      ["日本語を学ぶ", ["日本", "本語", "語を", "を学", "学ぶ", "ぶ"]],
      ["あいうえお", ["あい", "いう", "うえ", "えお", "お"]],
      ["カタカナ", ["カタ", "タカ", "カナ", "ナ"]],
      ["食べる", ["食べ", "べる", "る"]],
      ["東京タワー", ["東京", "京タ", "タワ", "ワー", "ー"]],
      ["東京リージョン", ["東京", "京リ", "リー", "ージ", "ジョ", "ョン", "ン"]],
      ["日日日", ["日日", "日日", "日"]],
      ["日本 株", ["日本", "本", "株"]],
    ]))("$input", ({ input, expected }) => {
      expectTokens(input, expected);
    });

    it("連続の長さ n に対してトークンは bi-gram n-1 個（と、設定が有効なら末尾 1 文字）", () => {
      for (let n = 1; n <= 30; n++) {
        expect(tokenize("あ".repeat(n))).toHaveLength(last || n === 1 ? n : n - 1);
      }
    });
  });

  describe("空・空白だけの入力", () => {
    it.each(["", " ", "　", "\t", "\n", "\r\n", " 　\t\n "])("%j は空", input => {
      expectTokens(input, []);
    });
  });

  describe("区切り文字で日本語の連続が切れる", () => {
    const separators = [
      " ", "　", "\t", "\n", "\r\n", " ",
      ",", ".", "，", "．", "、", "。", "､", "｡",
      ":", ";", "：", "；",
      "/", "\\", "／", "＼", "|", "｜",
      "-", "‐", "–", "—", "−", "_", "〜", "～", "~",
      "・", "･", "…", "‥",
      "!", "?", "！", "？", "+", "&", "#", "@", "%", "$", "^", "'", "\"", "’", "”",
      "(", ")", "（", "）", "「", "」", "『", "』", "【", "】", "〈", "〉", "《", "》", "〔", "〕", "<", ">", "{", "}",
      "※", "→", "★", "○", "●", "■", "◆", "♪", "〒", "¥", "￥", "_", "=", "[", "]",
      "🙂", "👨‍👩‍👧‍👦", "🇯🇵", "❤️",
    ];
    it.each(separators)("東京%s大阪", separator => {
      expectTokens(`東京${separator}大阪`, ["東京", "京", "大阪", "阪"]);
    });

    it("区切りが続いても空のトークンを作らない", () => {
      expectTokens("東京,,..、、　　大阪", ["東京", "京", "大阪", "阪"]);
    });

    it.each([
      ["(東京)「大阪」『京都』【神戸】〈奈良〉", ["東京", "京", "大阪", "阪", "京都", "都", "神戸", "戸", "奈良", "良"]],
      ["東京・大阪・名古屋", ["東京", "京", "大阪", "阪", "名古", "古屋", "屋"]],
      ["「重要」と言った", ["重要", "要", "と言", "言っ", "った", "た"]],
    ])("%s", (input, expected) => {
      expectTokens(input, expected);
    });
  });

  describe("見えない文字は取り除く", () => {
    it.each([
      ["ゼロ幅スペース", "東京​大阪"],
      ["ゼロ幅非接合子", "東京‌大阪"],
      ["ゼロ幅接合子", "東京‍大阪"],
      ["BOM", "﻿東京大阪"],
      ["ソフトハイフン", "東京­大阪"],
    ])("%s", (_name, input) => {
      expectTokens(input, ["東京", "京大", "大阪", "阪"]);
    });

    it.each([
      ["異体字セレクタ（IVS）", "葛\u{E0100}飾"],
      ["異体字セレクタ（SVS）", "葛︀飾"],
    ])("%s", (_name, input) => {
      expectTokens(input, ["葛飾", "飾"]);
    });

    it("単独の結合文字や異体字セレクタだけならトークンを作らない", () => {
      expectTokens("\u{E0100}", []);
      expectTokens("️", []);
    });
  });

  describe("全角・半角の寄せ（NFKC）", () => {
    it.each(cases([
      ["ＥＣ２", ["EC2"]],
      ["ＥC２", ["EC2"]],
      ["ＡＢＣ１２３", ["ABC123"]],
      ["ＥＣ２で建てた", ["EC2", "で建", "建て", "てた", "た"]],
      ["日本EC2設定", ["日本", "本", "EC2", "設定", "定"]],
      ["第１２回", ["第", "12", "回"]],
      ["2026年10月", ["2026", "年", "10", "月"]],
      ["２０２６年１０月３０日", ["2026", "年", "10", "月", "30", "日"]],
      ["ﾊﾟｿｺﾝ", ["パソ", "ソコ", "コン", "ン"]],
      ["ﾊﾟソｺン", ["パソ", "ソコ", "コン", "ン"]],
      ["ｻｰﾊﾞｰ", ["サー", "ーバ", "バー", "ー"]],
      ["ﾃﾞｰﾀﾍﾞｰｽ", ["デー", "ータ", "タベ", "ベー", "ース", "ス"]],
      ["ｶﾞｷﾞｸﾞｹﾞｺﾞ", ["ガギ", "ギグ", "グゲ", "ゲゴ", "ゴ"]],
      ["ﾊﾟﾋﾟﾌﾟﾍﾟﾎﾟ", ["パピ", "ピプ", "プペ", "ペポ", "ポ"]],
      ["ｳﾞｧｲｵﾘﾝ", ["ヴァ", "ァイ", "イオ", "オリ", "リン", "ン"]],
      ["がく", ["がく", "く"]],
      ["ぱん", ["ぱん", "ん"]],
      ["ガス", ["ガス", "ス"]],
      ["①", ["1"]],
      ["１", ["1"]],
      ["㍿", ["株式", "式会", "会社", "社"]],
      ["㈱ミカン", ["株", "ミカ", "カン", "ン"]],
      ["㌔", ["キロ", "ロ"]],
      ["㍉", ["ミリ", "リ"]],
      ["Ａ，Ｂ．Ｃ", ["A", "B", "C"]],
      ["ｍｅｅｔｉｎｇ", ["meeting"]],
      ["東京℃大阪", ["東京", "京", "C", "大阪", "阪"]],
      ["東京1️⃣大阪", ["東京", "京", "1", "大阪", "阪"]],
      ["東京～大阪", ["東京", "京", "大阪", "阪"]],
    ]))("$input", ({ input, expected }) => {
      expectTokens(input, expected);
    });

    it("大文字・小文字は変えない（小文字化は Silversearch が行う）", () => {
      expectTokens("ABC abc ＡＢＣ ａｂｃ", ["ABC", "abc", "ABC", "abc"]);
    });
  });

  describe("日本語以外の連続", () => {
    it.each(cases([
      ["meeting notes", ["meeting", "notes"]],
      ["foo-bar", ["foo", "bar"]],
      ["foo_bar", ["foo", "bar"]],
      ["foo.bar", ["foo", "bar"]],
      ["fooBar", ["fooBar"]],
      ["C++ C# .NET", ["C", "C", "NET"]],
      ["1,000 3.14 v1.2.5", ["1", "000", "3", "14", "v1", "2", "5"]],
      ["https://example.com/a/b", ["https", "example", "com", "a", "b"]],
      ["user@example.com", ["user", "example", "com"]],
      ["Crème brûlée", ["Crème", "brûlée"]],
      ["한국어 Русский", ["한국어", "Русский"]],
    ]))("$input", ({ input, expected }) => {
      expectTokens(input, expected);
    });

    it.each(cases([
      ["AWSの請求書", ["AWS", "の請", "請求", "求書", "書"]],
      ["S3バケット", ["S3", "バケ", "ケッ", "ット", "ト"]],
      ["Dockerで起動", ["Docker", "で起", "起動", "動"]],
      ["東京API", ["東京", "京", "API"]],
      ["ver1.2.3の話", ["ver1", "2", "3", "の話", "話"]],
      ["値段は1,000円", ["値段", "段は", "は", "1", "000", "円"]],
      ["Crème brûléeと한국어", ["Crème", "brûlée", "と", "한국어"]],
    ]))("日本語との境界で切れる: $input", ({ input, expected }) => {
      expectTokens(input, expected);
    });
  });

  describe("日本語の文字の範囲", () => {
    it.each(cases([
      ["佐々木", ["佐々", "々木", "木"]],
      ["人々", ["人々", "々"]],
      ["時々刻々", ["時々", "々刻", "刻々", "々"]],
      ["〆切", ["〆切", "切"]],
      ["〇月〇日", ["〇月", "月〇", "〇日", "日"]],
      ["𠮷野家", ["𠮷野", "野家", "家"]],
      ["𠮷", ["𠮷"]],
      ["𩸽の塩焼き", ["𩸽の", "の塩", "塩焼", "焼き", "き"]],
      ["一ヶ月", ["一ヶ", "ヶ月", "月"]],
      ["ヵ月", ["ヵ月", "月"]],
      ["こゝろ", ["こゝ", "ゝろ", "ろ"]],
      ["いすゞ", ["いす", "すゞ", "ゞ"]],
      ["きゃく", ["きゃ", "ゃく", "く"]],
      ["ユーザー", ["ユー", "ーザ", "ザー", "ー"]],
      ["ーー", ["ーー", "ー"]],
      ["ヴ", ["ヴ"]],
      ["髙橋", ["髙橋", "橋"]],
      ["國際", ["國際", "際"]],
      ["﨑", ["﨑"]],
    ]))("$input", ({ input, expected }) => {
      expectTokens(input, expected);
    });

    it.each(["・", "･", "、", "。", "「", "」", "〜", "゛", "゜", "\u3099", "\u309a"])("%j だけならトークンを作らない", input => {
      expectTokens(input, []);
    });

    it.each(cases([
      ["あ\u3099い", ["あ\u3099い", "い"]],
      ["ア\u309aイ", ["ア\u309aイ", "イ"]],
      ["\u3099あい", ["あい", "い"]],
      ["東京゛大阪", ["東京", "京", "大阪", "阪"]],
    ]))("合成できない濁点は前の文字と 1 文字として扱う: $input", ({ input, expected }) => {
      expectTokens(input, expected);
    });
  });

  describe("Markdown の記号を挟んだ日本語", () => {
    it.each(cases([
      ["**重要**な話", ["重要", "要な", "な話", "話"]],
      ["*強調*された", ["強調", "調さ", "され", "れた", "た"]],
      ["__重要__です", ["重要", "要で", "です", "す"]],
      ["~~削除~~した", ["削除", "除し", "した", "た"]],
      ["==注目==の件", ["注目", "目の", "の件", "件"]],
      ["`設定`を変える", ["設定", "定を", "を変", "変え", "える", "る"]],
      ["[[会議メモ]]の件", ["会議", "議メ", "メモ", "モの", "の件", "件"]],
      ["詳細は[[会議メモ]]へ", ["詳細", "細は", "は会", "会議", "議メ", "メモ", "モへ", "へ"]],
    ]))("$input", ({ input, expected }) => {
      expectTokens(input, expected);
    });

    it.each(cases([
      ["[リンク](https://example.com)を参照", ["リン", "ンク", "ク", "https", "example", "com", "を参", "参照", "照"]],
      ["# 見出し", ["見出", "出し", "し"]],
      ["- [ ] 宿題", ["宿題", "題"]],
      ["> 引用文", ["引用", "用文", "文"]],
      ["#タグ", ["タグ", "グ"]],
      ["foo_bar_日本", ["foo", "bar", "日本", "本"]],
    ]))("日本語に挟まれていない記号は区切りのまま: $input", ({ input, expected }) => {
      expectTokens(input, expected);
    });
  });

  describe("isTokenizable", () => {
    it.each([
      ["日本語", true],
      ["東京", true],
      ["ｱｲｳ", true],
      ["𠮷", true],
      ["々", true],
      ["ー", true],
      ["meeting notes 請求", true],
      ["EC2の設定", true],
      ["ＥＣ２", true],
      ["①", true],
      ["㌔", true],
      ["Ａ，Ｂ", true],
      ["が", true],
      ["", false],
      ["hello world", false],
      ["EC2", false],
      ["12345", false],
      ["Crème brûlée", false],
      ["한국어", false],
      ["🙂", false],
      ["・", false],
      ["、。", false],
    ])("%j は %s", (input, expected) => {
      expect(isTokenizable(input)).toBe(expected);
    });

    it("同じ入力を繰り返し判定しても結果が変わらない", () => {
      for (let i = 0; i < 5; i++) {
        expect(isTokenizable("東京")).toBe(true);
        expect(isTokenizable("hello")).toBe(false);
      }
    });

    it("日本語を含まないが NFKC で変わる文字は、受け付けても空の結果になりうる", () => {
      expect(isTokenizable("･")).toBe(true);
      expectTokens("･", []);
    });
  });
});
